import {
  HUMAN_PARTICIPANT,
  PHASE_TITLES,
  type ContributionRequest,
  type ConvergenceAssessment,
  type Participant,
} from '../../domain';
import type { ContributionProvider, ProviderRegistry, ProviderResult } from '../../ports';
import { DEFAULT_PACE_ID, simulationPace, type SimulationPaceId, type SimulationScenarioId } from './scenarios';
import { PERSONA_SCRIPTS, SCRIPTED_FAILURES, type PersonaScript, type SimulatedPersonaId } from './scripts';

export const SIMULATION_PARTICIPANTS: readonly Participant[] = [
  HUMAN_PARTICIPANT,
  { id: 'gpt', displayName: PERSONA_SCRIPTS.gpt.displayName, providerType: 'gpt-simulator' },
  { id: 'claude', displayName: PERSONA_SCRIPTS.claude.displayName, providerType: 'claude-simulator' },
];

export interface SimulatedProviderOptions {
  readonly persona: SimulatedPersonaId;
  readonly scenario: SimulationScenarioId;
  /** Artificial latency, so concurrency and pausing are observable in the UI. */
  readonly delayMs: number;
}

/**
 * Deterministic stand-in for a real provider. The same request and scenario
 * always produce the same result. It never contacts any external service.
 */
export function createSimulatedProvider(options: SimulatedProviderOptions): ContributionProvider {
  const script = PERSONA_SCRIPTS[options.persona];
  return {
    participantId: script.participantId,
    origin: 'simulated',
    supportsCancellation: true,
    async requestContribution(request, { signal }) {
      await wait(options.delayMs, signal);
      return simulateContribution(script, options.scenario, request);
    },
  };
}

export interface SimulatedProvidersOptions {
  readonly gptDelayMs: number;
  readonly claudeDelayMs: number;
}

/** Slightly different delays make the concurrent first round visible. */
export const DEFAULT_SIMULATED_DELAYS: SimulatedProvidersOptions = delaysForPace(DEFAULT_PACE_ID);

export function delaysForPace(pace: SimulationPaceId): SimulatedProvidersOptions {
  const { gptDelayMs, claudeDelayMs } = simulationPace(pace);
  return { gptDelayMs, claudeDelayMs };
}

export function createSimulatedProviders(
  scenario: SimulationScenarioId,
  delays: SimulatedProvidersOptions = DEFAULT_SIMULATED_DELAYS,
): ProviderRegistry {
  return new Map([
    ['gpt', createSimulatedProvider({ persona: 'gpt', scenario, delayMs: delays.gptDelayMs })],
    ['claude', createSimulatedProvider({ persona: 'claude', scenario, delayMs: delays.claudeDelayMs })],
  ]);
}

/** Pure core of the simulator, exposed for tests. */
export function simulateContribution(
  script: PersonaScript,
  scenario: SimulationScenarioId,
  request: ContributionRequest,
): ProviderResult {
  const failure = SCRIPTED_FAILURES[scenario];
  if (failure !== null && failure.persona === script.participantId && failure.phase === request.phase) {
    return {
      ok: false,
      error: {
        message: `Simulated failure: the ${script.displayName} is scripted to fail during ${PHASE_TITLES[request.phase]} in this scenario.`,
      },
    };
  }
  return {
    ok: true,
    content: composeContent(script, request),
    assessment: composeAssessment(script, scenario, request),
  };
}

function composeContent(script: PersonaScript, request: ContributionRequest): string {
  const phase = script.phases[request.phase];
  const lines: string[] = [`Position: ${phase.position.replace('{topic}', quoteTopic(request.topic))}`];

  const opponent = request.priorContributions
    .filter((prior) => prior.round === request.round - 1 && prior.participantId !== script.participantId)
    .at(-1);
  if (opponent !== undefined) {
    lines.push('', `Responding to ${opponent.displayName}: “${firstPositionLine(opponent.content)}”`);
  }

  lines.push('', `${phase.heading}:`, ...phase.points.map((point) => `- ${point}`));

  lines.push('', 'Constraints respected:');
  if (request.constraints.length === 0) {
    lines.push('- No constraints were supplied.');
  }
  for (const constraint of request.constraints) {
    lines.push(
      constraint.source === 'session'
        ? `- “${constraint.text}”: the position above stays within this constraint.`
        : `- “${constraint.text}” (added by the human during the debate): taken into account in this contribution.`,
    );
  }

  lines.push(
    '',
    `[Simulated output generated by the ThirdMind ${script.displayName}. This is not a response from ${script.standsInFor}.]`,
  );
  return lines.join('\n');
}

function composeAssessment(
  script: PersonaScript,
  scenario: SimulationScenarioId,
  request: ContributionRequest,
): ConvergenceAssessment {
  const scripted = script.assessments[scenario][request.phase];
  const humanConstraintAgreements = request.constraints.flatMap((constraint) =>
    constraint.source === 'human-intervention' ? [`Respect the human constraint: “${constraint.text}”.`] : [],
  );
  return {
    materialIssues: scripted.materialIssues,
    openQuestions: scripted.openQuestions,
    agreements: [...scripted.agreements, ...humanConstraintAgreements],
  };
}

function quoteTopic(topic: string): string {
  const shortened = topic.length > 120 ? `${topic.slice(0, 117)}...` : topic;
  return `“${shortened}”`;
}

function firstPositionLine(content: string): string {
  const line = content.split('\n').find((l) => l.startsWith('Position:')) ?? content.split('\n')[0] ?? '';
  return line.replace(/^Position:\s*/, '');
}

function wait(milliseconds: number, signal: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal.aborted) {
      reject(new Error('The simulated request was cancelled.'));
      return;
    }
    const onAbort = (): void => {
      clearTimeout(timer);
      reject(new Error('The simulated request was cancelled.'));
    };
    const timer = setTimeout(() => {
      signal.removeEventListener('abort', onAbort);
      resolve();
    }, Math.max(0, milliseconds));
    signal.addEventListener('abort', onAbort, { once: true });
  });
}
