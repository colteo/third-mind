import type { ExecutionMode } from '../../application';
import type { DebateStatus } from '../../domain';
import type { ConnectionStatus } from '../../extension/side-panel-client';
import { statusLabel } from '../format';

interface HeaderProps {
  readonly status: DebateStatus | null;
  readonly connection: ConnectionStatus;
  /** Mode of the current session, or the mode selected for the next one. */
  readonly mode: ExecutionMode;
}

const MODE_BADGES: Readonly<Record<ExecutionMode, { readonly label: string; readonly title: string }>> = {
  simulation: {
    label: 'Simulation mode',
    title: 'Every participant response is generated by a deterministic local simulator. No AI service is contacted.',
  },
  live: {
    label: 'Browser Conversations',
    title:
      'Links existing and empty ChatGPT and Claude chats. Autonomous submission and reply acquisition are unavailable; readiness blocks browser debate execution.',
  },
};

export function Header({ status, connection, mode }: HeaderProps) {
  const tone = connection === 'connected' ? (status?.kind ?? 'none') : 'connecting';
  const badge = MODE_BADGES[mode];
  return (
    <header className="header">
      <h1 className="brand">ThirdMind</h1>
      <div className="header-meta">
        <span className={`badge badge-${mode}`} title={badge.title}>
          {badge.label}
        </span>
        <span className={`status status-${tone}`} role="status" aria-live="polite">
          <span className="visually-hidden">Session status: </span>
          {statusLabel(status, connection)}
        </span>
      </div>
    </header>
  );
}
