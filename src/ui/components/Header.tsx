import type { DebateStatus } from '../../domain';
import type { ConnectionStatus } from '../../extension/side-panel-client';
import { statusLabel } from '../format';

interface HeaderProps {
  readonly status: DebateStatus | null;
  readonly connection: ConnectionStatus;
}

export function Header({ status, connection }: HeaderProps) {
  const tone = connection === 'connected' ? (status?.kind ?? 'none') : 'connecting';
  return (
    <header className="header">
      <h1 className="brand">ThirdMind</h1>
      <div className="header-meta">
        <span
          className="badge badge-simulation"
          title="Every participant response is generated by a deterministic local simulator. No AI service is contacted."
        >
          Simulation mode
        </span>
        <span className={`status status-${tone}`} role="status" aria-live="polite">
          <span className="visually-hidden">Session status: </span>
          {statusLabel(status, connection)}
        </span>
      </div>
    </header>
  );
}
